#!/usr/bin/env node
/**
 * Exports the current message catalogue as Sanity-importable NDJSON.
 *
 * WHY THIS EXISTS
 * ---------------
 * The alternative to this script is a person retyping every page of the site
 * into a Studio, in two languages, from a source that is still changing. That
 * introduces drift on day one: the CMS says one thing, the repository says
 * another, and nobody can tell which is live.
 *
 * So the CMS starts as an exact copy of what is already published, and the
 * first thing an editor sees is the real site content. Anything they do from
 * there is a deliberate edit rather than a re-entry error.
 *
 * Only the namespaces in content/cms-namespaces.json are exported. Legal and
 * safety copy is not editable in the CMS by design — see that file.
 *
 * Usage:
 *   node scripts/export-content-for-cms.mjs
 *   → review/cms-seed.ndjson
 *
 * Then, with the Sanity CLI in the Studio project:
 *   npx sanity dataset import review/cms-seed.ndjson production
 */

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MESSAGES_DIR = join(ROOT, "content", "messages");
const OUT_DIR = join(ROOT, "review");
const OUT_FILE = join(OUT_DIR, "cms-seed.ndjson");

const LOCALES = ["en", "fr"];
const REVIEW_MARKER_KEY = "_translationReview";

const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));

const { cmsManaged } = readJson(join(ROOT, "content", "cms-namespaces.json"));

/** Must match `sanityTypeFor` in lib/cms.ts and the schema generator. */
const typeNameFor = (namespace) =>
  `messages_${namespace.replace(/[^a-zA-Z0-9]/g, "_")}`;

/**
 * Sanity requires a `_key` on every item of an array of objects — without one
 * the Studio refuses to render the list and shows a "missing keys" repair
 * prompt instead. Keys are positional and stable so re-importing updates items
 * in place rather than shuffling them.
 *
 * `_type` on those items matches the inline object type the schema generator
 * emits (`<field>Item`), so the Studio knows which fields to show.
 */
function withSanityKeys(value, fieldName = "") {
  if (Array.isArray(value)) {
    return value.map((item, index) => {
      const mapped = withSanityKeys(item, fieldName);
      if (mapped && typeof mapped === "object" && !Array.isArray(mapped)) {
        return { _key: `k${index}`, _type: `${fieldName}Item`, ...mapped };
      }
      return mapped;
    });
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => [k, withSanityKeys(v, k)]),
    );
  }

  return value;
}

/**
 * A message FILE may contain more than one namespace at its top level (for
 * example safeher.json carries both `safeher` and `regions`). The CMS is
 * organised by namespace, not by file, so every top-level key is considered
 * and only the managed ones are emitted.
 */
function namespacesIn(dir) {
  const map = new Map();
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    const doc = readJson(join(dir, file));
    for (const [namespace, content] of Object.entries(doc)) {
      if (namespace === REVIEW_MARKER_KEY) continue;
      map.set(namespace, content);
    }
  }
  return map;
}

const documents = [];
const summary = [];

for (const locale of LOCALES) {
  const available = namespacesIn(join(MESSAGES_DIR, locale));
  const found = new Map();

  for (const namespace of cmsManaged) {
    const content = available.get(namespace);

    if (content === undefined) {
      console.warn(
        `  ! ${locale}: namespace "${namespace}" not found — skipped`,
      );
      continue;
    }

    found.set(namespace, content);

    documents.push({
      // Deterministic ID: re-running the import updates the same documents
      // instead of creating duplicates.
      _id: `${typeNameFor(namespace)}.${locale}`,
      _type: typeNameFor(namespace),
      namespace,
      locale,
      // The namespace's message tree as structured content, matching the schema
      // generated by build-sanity-schema.mjs. Structured rather than a JSON
      // blob so an editor gets real labelled fields instead of a textarea full
      // of braces — which is the entire reason for having a CMS.
      content: withSanityKeys(content),
      title: `${namespace} (${locale})`,
    });
  }

  summary.push(`${locale}: ${found.size}/${cmsManaged.length} namespaces`);
}

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(
  OUT_FILE,
  documents.map((d) => JSON.stringify(d)).join("\n") + "\n",
  "utf8",
);

console.log(`Wrote ${documents.length} documents to review/cms-seed.ndjson`);
for (const line of summary) console.log(`  ${line}`);
console.log(
  `\nNot exported (deliberately code-managed): legal, safety, common,`,
);
console.log(`contact, get-involved, portal. See content/cms-namespaces.json.`);
